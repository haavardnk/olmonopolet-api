CHRISTMAS_PATTERN = re.compile("|".join(CHRISTMAS_KEYWORDS), re.IGNORECASE)


def christmas_reason(beer: Beer) -> str | None:
    if beer.vmp_id in KNOWN_CHRISTMAS_BEERS:
        return "known list"
    if CHRISTMAS_PATTERN.search(beer.vmp_name):
        return "keyword match"
    return None


def mark_christmas_beers() -> None:
    print("Starting to mark Christmas beers...\n")

    marked = 0
    for beer in Beer.objects.all():
        reason = christmas_reason(beer)
        if reason is None:
            continue
        beer.is_christmas_beer = True
        beer.save(update_fields=["is_christmas_beer"])
        marked += 1
        print(f"✓ Marked as Christmas beer ({reason}): {beer.vmp_name}")

    print(f"\n{'=' * 60}")
    print(f"Total marked as Christmas beers: {marked}/{Beer.objects.count()}")
    print(f"{'=' * 60}")


if __name__ == "__main__":
    mark_christmas_beers()
